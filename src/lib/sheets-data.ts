import { prisma } from "@/lib/prisma";
import { formatInTimeZone } from "date-fns-tz";
import { TIMEZONE } from "@/lib/constants";
import type { SheetData } from "@/lib/google-sheets";

/** Fetch all dashboard data and format as SheetData[] for Google Sheets export */
export async function buildBackupSheetData(): Promise<SheetData[]> {
  const [tasks, shifts, links, jobs, media, sites, loginLogs, diary, emailLogs, pushSubscriptions, notificationLogs, contacts, chatConversations, importantTopics, tennisRackets, tennisSessions, strokeRatings, tennisNotes, stringInventory, tennisStages, tennisRatings] = await Promise.all([
    prisma.task.findMany({ orderBy: { createdAt: "desc" }, include: { photos: true } }),
    prisma.shift.findMany({ orderBy: { date: "desc" } }),
    prisma.link.findMany({ orderBy: { order: "asc" } }),
    prisma.jobApplication.findMany({ orderBy: { dateApplied: "desc" } }),
    prisma.mediaFile.findMany({ orderBy: { createdAt: "desc" } }),
    prisma.monitoredSite.findMany({ orderBy: { order: "asc" } }),
    prisma.loginLog.findMany({ orderBy: { createdAt: "desc" } }),
    prisma.diaryEntry.findMany({ orderBy: { date: "desc" }, include: { photos: true, links: true } }),
    prisma.emailLog.findMany({ orderBy: { createdAt: "desc" } }),
    prisma.pushSubscription.findMany({ orderBy: { createdAt: "desc" } }),
    prisma.notificationLog.findMany({ orderBy: { sentAt: "desc" } }),
    prisma.contact.findMany({ orderBy: { name: "asc" } }),
    prisma.chatConversation.findMany({ orderBy: { updatedAt: "desc" }, include: { messages: { orderBy: { createdAt: "asc" } } } }),
    prisma.importantTopic.findMany({ orderBy: { order: "asc" }, include: { items: true } }),
    prisma.tennisRacket.findMany({ orderBy: { createdAt: "desc" }, include: { photos: true, restrings: { include: { photos: true } } } }),
    prisma.tennisSession.findMany({ orderBy: { date: "desc" }, include: { racket: true } }),
    prisma.strokeRating.findMany({ orderBy: { date: "desc" } }),
    prisma.tennisNote.findMany({ orderBy: { createdAt: "desc" } }),
    prisma.stringInventory.findMany({ orderBy: { createdAt: "desc" }, include: { photos: true } }),
    prisma.tennisStage.findMany({ orderBy: { stageNumber: "asc" }, include: { ratings: true } }),
    prisma.tennisRating.findMany({ orderBy: { date: "desc" }, include: { stage: { select: { stageNumber: true, stageLabel: true } } } }),
  ]);

  return [
    {
      title: "Tasks",
      headers: ["Title", "Description", "Status", "Priority", "Due Date", "Category", "Photos", "Created"],
      rows: tasks.map((t) => [
        t.title,
        t.description ?? "",
        t.status,
        t.priority,
        t.dueDate ? formatInTimeZone(t.dueDate, TIMEZONE, "yyyy-MM-dd") : "",
        t.category ?? "",
        t.photos.length.toString(),
        formatInTimeZone(t.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Shifts",
      headers: ["Date", "Day", "Start", "End", "Location", "Label", "Hours", "Gross Pay", "Net Pay", "Notes"],
      rows: shifts.map((s) => [
        formatInTimeZone(s.date, TIMEZONE, "yyyy-MM-dd"),
        formatInTimeZone(s.date, TIMEZONE, "EEE"),
        formatInTimeZone(s.startTime, TIMEZONE, "HH:mm"),
        formatInTimeZone(s.endTime, TIMEZONE, "HH:mm"),
        s.location,
        s.label ?? "",
        s.hours.toString(),
        `$${s.grossPay.toFixed(2)}`,
        `$${s.netPay.toFixed(2)}`,
        s.notes ?? "",
      ]),
    },
    {
      title: "Links",
      headers: ["Label", "URL", "Icon", "Order"],
      rows: links.map((l) => [
        l.label,
        l.url,
        l.icon ?? "",
        l.order.toString(),
      ]),
    },
    {
      title: "Media",
      headers: ["Filename", "Title", "Type", "Size", "Tags", "Public", "Views", "Downloads", "Share Slug", "Created"],
      rows: media.map((m) => [
        m.filename,
        m.title ?? "",
        m.mimeType,
        m.size.toString(),
        m.tags.join("; "),
        m.isPublic ? "Yes" : "No",
        m.views.toString(),
        m.downloads.toString(),
        m.shareSlug,
        formatInTimeZone(m.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Applications",
      headers: [
        "#",
        "Title",
        "Company",
        "Status",
        "Date Applied",
        "Next Steps",
        "Salary",
        "Location",
        "URL",
        "Assessment Type",
        "Assessment Notes",
        "Notes",
      ],
      rows: jobs.map((j) => [
        j.order.toString(),
        j.title,
        j.company,
        j.status,
        formatInTimeZone(j.dateApplied, TIMEZONE, "yyyy-MM-dd"),
        j.nextSteps ?? "",
        j.salary ?? "",
        j.location ?? "",
        j.jobUrl ?? "",
        j.assessmentType ?? "NONE",
        j.assessmentNotes ?? "",
        j.notes ?? "",
      ]),
    },
    {
      title: "Monitored Sites",
      headers: ["Label", "URL", "Order", "Created"],
      rows: sites.map((s) => [
        s.label,
        s.url,
        s.order.toString(),
        formatInTimeZone(s.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Login Logs",
      headers: ["Email", "Name", "Success", "IP", "User Agent", "Timestamp"],
      rows: loginLogs.map((l) => [
        l.email,
        l.name ?? "",
        l.success ? "Yes" : "No",
        l.ip ?? "",
        l.userAgent ?? "",
        formatInTimeZone(l.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Email Logs",
      headers: ["Type", "To", "Subject", "Preview", "Sent"],
      rows: emailLogs.map((e) => [
        e.type,
        e.to,
        e.subject,
        e.preview ?? "",
        formatInTimeZone(e.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Diary",
      headers: ["Date", "Mood", "Tags", "Content", "Word Count", "Media", "Links", "Created"],
      rows: diary.map((d) => [
        formatInTimeZone(d.date, TIMEZONE, "yyyy-MM-dd"),
        d.mood ?? "",
        d.tags.join("; "),
        d.content ?? "",
        d.content ? d.content.split(/\s+/).length.toString() : "0",
        d.photos.length.toString(),
        d.links.length.toString(),
        formatInTimeZone(d.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Push Subscriptions",
      headers: ["Device", "Endpoint", "Created"],
      rows: pushSubscriptions.map((p) => [
        p.device ?? "Unknown",
        p.endpoint,
        formatInTimeZone(p.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Contacts",
      headers: ["Name", "Email", "Phone", "Company", "Title", "Tags", "Notes", "Photo", "Google ID", "Last Synced", "Created"],
      rows: contacts.map((c) => [
        c.name,
        c.email ?? "",
        c.phone ?? "",
        c.company ?? "",
        c.title ?? "",
        c.tags.join("; "),
        c.notes ?? "",
        c.photoUrl ?? "",
        c.googleContactId ?? "",
        c.lastSyncedAt ? formatInTimeZone(c.lastSyncedAt, TIMEZONE, "yyyy-MM-dd HH:mm") : "",
        formatInTimeZone(c.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Notification Logs",
      headers: ["Type", "Reference ID", "Sent At"],
      rows: notificationLogs.map((n) => [
        n.type,
        n.refId,
        formatInTimeZone(n.sentAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Important Topics",
      headers: ["Title", "Icon", "Category", "Pinned", "Items", "Created", "Updated"],
      rows: importantTopics.map((t) => [
        t.title,
        t.icon ?? "",
        t.category ?? "",
        t.pinned ? "Yes" : "No",
        t.items.length.toString(),
        formatInTimeZone(t.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
        formatInTimeZone(t.updatedAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Important Items",
      headers: ["Topic", "Type", "Label", "URL", "Content", "Pinned", "Created"],
      rows: importantTopics.flatMap((t) =>
        t.items.map((i) => [
          t.title,
          i.type,
          i.label ?? "",
          i.url ?? "",
          i.content ? (i.content.length > 500 ? i.content.slice(0, 500) + "..." : i.content) : "",
          i.pinned ? "Yes" : "No",
          formatInTimeZone(i.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
        ])
      ),
    },
    {
      title: "Chat History",
      headers: ["Conversation", "Role", "Content", "Tools", "Input Tokens", "Output Tokens", "Cache Read", "Sent"],
      rows: chatConversations.flatMap((c) =>
        c.messages.map((m) => [
          c.title ?? c.id.slice(0, 8),
          m.role,
          m.content.length > 500 ? m.content.slice(0, 500) + "..." : m.content,
          m.toolCalls.join(", "),
          m.inputTokens?.toString() ?? "",
          m.outputTokens?.toString() ?? "",
          m.cacheReadTokens?.toString() ?? "",
          formatInTimeZone(m.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
        ])
      ),
    },
    {
      title: "Tennis Rackets",
      headers: ["Name", "Brand", "Model", "Weight", "Head Size", "Balance", "Current String", "Tension", "Last Strung", "Restrings", "Photos", "Notes", "Created"],
      rows: tennisRackets.map((r) => [
        r.name,
        r.brand ?? "",
        r.model ?? "",
        r.weight?.toString() ?? "",
        r.headSize?.toString() ?? "",
        r.balance?.toString() ?? "",
        r.currentString ?? "",
        r.tension ?? "",
        r.lastStrung ? formatInTimeZone(r.lastStrung, TIMEZONE, "yyyy-MM-dd") : "",
        r.restrings.length.toString(),
        r.photos.length.toString(),
        r.notes ?? "",
        formatInTimeZone(r.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Tennis Sessions",
      headers: ["Date", "Type", "Duration (hrs)", "Racket", "Coach", "Location", "Played With", "Calendar Event", "Tags", "Notes", "Created"],
      rows: tennisSessions.map((s) => [
        formatInTimeZone(s.date, TIMEZONE, "yyyy-MM-dd"),
        s.type,
        s.duration?.toString() ?? "",
        s.racket?.name ?? "",
        s.coach ?? "",
        s.location ?? "",
        s.playedWith ?? "",
        s.calendarEventTitle ?? "",
        s.tags.join("; "),
        s.notes ?? "",
        formatInTimeZone(s.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "Stroke Ratings (Legacy)",
      headers: ["Date", "Stroke", "Rating", "Session ID"],
      rows: strokeRatings.map((r) => [
        formatInTimeZone(r.date, TIMEZONE, "yyyy-MM-dd"),
        r.stroke,
        r.rating.toString(),
        r.sessionId ?? "",
      ]),
    },
    {
      title: "Tennis Stages",
      headers: ["Stage #", "Label", "UTR Range", "Active", "Started", "Completed", "Ratings"],
      rows: tennisStages.map((s) => [
        s.stageNumber.toString(),
        s.stageLabel,
        s.utrRange,
        s.isActive ? "Yes" : "No",
        formatInTimeZone(s.startedAt, TIMEZONE, "yyyy-MM-dd"),
        s.completedAt ? formatInTimeZone(s.completedAt, TIMEZONE, "yyyy-MM-dd") : "",
        s.ratings?.length?.toString() ?? "0",
      ]),
    },
    {
      title: "Tennis Ratings",
      headers: ["Date", "Stage", "Rated By", "FH", "BH Topspin", "BH Slice", "Serve", "Volley", "Overhead", "Return", "Notes"],
      rows: tennisRatings.map((r) => [
        formatInTimeZone(r.date, TIMEZONE, "yyyy-MM-dd"),
        `${r.stage.stageNumber} - ${r.stage.stageLabel}`,
        r.ratedBy,
        r.forehand.toFixed(1),
        r.bhTopspin.toFixed(1),
        r.bhSlice.toFixed(1),
        r.serve.toFixed(1),
        r.volley.toFixed(1),
        r.overhead.toFixed(1),
        r.returnOf.toFixed(1),
        r.notes ?? "",
      ]),
    },
    {
      title: "Tennis Notes",
      headers: ["Content", "Tags", "Pinned", "Created"],
      rows: tennisNotes.map((n) => [
        n.content,
        n.tags.join("; "),
        n.pinned ? "Yes" : "No",
        formatInTimeZone(n.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
    {
      title: "String Inventory",
      headers: ["Name", "Type", "Gauge", "Quantity", "Photos", "Notes", "Created"],
      rows: stringInventory.map((s) => [
        s.name,
        s.type,
        s.gauge ?? "",
        s.quantity.toString(),
        s.photos.length.toString(),
        s.notes ?? "",
        formatInTimeZone(s.createdAt, TIMEZONE, "yyyy-MM-dd HH:mm"),
      ]),
    },
  ];
}
